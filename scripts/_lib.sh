#!/usr/bin/env bash
# =============================================================================
# scripts/_lib.sh — shared helpers and env-var validation
# =============================================================================
# Sourced by run_*.sh. Reads required configuration from environment variables
# (see README.md → Setup for the full list and what each one points at).
#
# Fails loudly with a pointer to the README if any required var is unset.
# =============================================================================

timestamp() { date +"%y%m%d_%H%M%S"; }
ensure_dir() { mkdir -p "$1"; }

log_start() {
  echo "========================================"
  echo " $1"
  echo " Started: $(date)"
  echo "========================================"
}
log_done() {
  echo "========================================"
  echo " $1 — DONE"
  echo " Finished: $(date)"
  echo "========================================"
}

# require_env VAR1 VAR2 ... — error out if any are unset/empty
require_env() {
  local missing=0
  for v in "$@"; do
    if [ -z "${!v:-}" ]; then
      echo "ERROR: env var \$${v} is not set." >&2
      missing=1
    fi
  done
  if [ "$missing" -ne 0 ]; then
    echo "" >&2
    echo "See README.md → Setup for the full list of env vars the pipeline expects." >&2
    exit 1
  fi
}

# require_file_executable PATH — error if the file isn't there or not executable
require_file_executable() {
  local p="$1" label="${2:-binary}"
  if [ ! -x "$p" ]; then
    echo "ERROR: ${label} not found or not executable at: $p" >&2
    echo "See README.md → Setup for installation instructions." >&2
    exit 1
  fi
}

# Reasonable default for RAD threads if the user didn't pin one.
: "${RAD_THREADS:=4}"
export RAD_THREADS

# Derived paths that several run scripts share.
if [ -n "${RAW_FQ:-}" ]; then
  : "${SCTAGGER_SIM:=${RAW_FQ}/sctagger_sim/long-reads}"
  : "${SCTAGGER_TRUTH:=${RAW_FQ}/sctagger_sim/truth}"
  : "${RAGESEQ_FQ:=${RAW_FQ}/rageseq.fq.gz}"
  : "${SCMIX2_FQ:=${RAW_FQ}/scmix2.fq.gz}"
  : "${SPLITSEQ_FQ:=${RAW_FQ}/splitseq.fq.gz}"
  : "${NBC_BCR_FQ:=${RAW_FQ}/nbc_bcr_data.fq.gz}"
  : "${SPATIAL_FQ:=${RAW_FQ}/spatial_tonsil_data/compiled_spatial_renamed.fq.gz}"
  export SCTAGGER_SIM SCTAGGER_TRUTH RAGESEQ_FQ SCMIX2_FQ SPLITSEQ_FQ NBC_BCR_FQ SPATIAL_FQ
fi

if [ -n "${WL_DIR:-}" ]; then
  : "${SCMIX2_WL:=${WL_DIR}/scmix2_barcodes.csv}"
  : "${NBC_WL:=${WL_DIR}/nbc_barcodes.csv}"
  : "${RAGESEQ_WL:=${WL_DIR}/rageseq_autogenerated_bcs.txt}"
  : "${RAGESEQ_FULL_WL:=${WL_DIR}/rageseq_full_bcs.csv}"
  : "${RAGESEQ_DUMMY_WL:=${WL_DIR}/rageseq_dummy_bcs/rageseq_dummy_bcs_v1.csv}"
  : "${SCTAGGER_GEN_WL:=${WL_DIR}/sctagger_rad_generated.csv}"
  export SCMIX2_WL NBC_WL RAGESEQ_WL RAGESEQ_FULL_WL RAGESEQ_DUMMY_WL SCTAGGER_GEN_WL
fi

if [ -n "${WL_DETECTION_RESULTS:-}" ]; then
  : "${VISIUM_WL_DIR:=${WL_DETECTION_RESULTS}/120525_visium_data_results}"
  export VISIUM_WL_DIR
fi

if [ -n "${PROJECT_SCRIPTS:-}" ]; then
  : "${EXTRACT_HEADERS:=${PROJECT_SCRIPTS}/extract_rad_headers_new.sh}"
  export EXTRACT_HEADERS
fi
