# =============================================================================
# Helper functions
# =============================================================================

timestamp() {
  date +"%y%m%d_%H%M%S"
}

ensure_dir() {
  mkdir -p "$1"
}

log_start() {
  echo "========================================"
  echo " $1"
  echo " Started: $(date)"
  echo "========================================"
}

log_done() {
  echo "========================================"
  echo " $1 — DONE"
  echo " Finished: $(date)"
  echo "========================================"
}

# Confirm the configured raw-FASTQ + results roots exist before any figure runs.
check_paths() {
  local missing=0
  for var in RAW_FQ RESULTS_BASE; do
    local val="${!var}"
    if [ -z "$val" ] || [ ! -d "$val" ]; then
      echo "ERROR: $var=$val does not exist." >&2
      missing=1
    fi
  done
  if [ "$missing" -ne 0 ]; then
    echo "Set the missing paths in config.sh or config.local.sh." >&2
    exit 1
  fi
}

# Back-compat alias: older figure scripts call check_ssd.
check_ssd() { check_paths; }

check_rad() {
  if [ ! -x "$RAD_BIN" ]; then
    echo "ERROR: rad binary not found or not executable at $RAD_BIN" >&2
    echo "Set RAD_BIN in config.sh or config.local.sh." >&2
    exit 1
  fi
}
