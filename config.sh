check_ssd() {
  if [ ! -d "/Volumes/CMV_SSD_2" ]; then
    echo "ERROR: External SSD not mounted at /Volumes/CMV_SSD_2"
    echo "Please connect the drive and try again."
    exit 1
  fi
}

