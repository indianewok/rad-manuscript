export SCTAGGER_GEN_WL="${SCTAGGER_GEN_WL:-${WL_DIR}/sctagger_rad_generated.csv}"

# --- Whitelist detection sub-dirs (derived from WL_DETECTION_RESULTS) -------
export VISIUM_WL_DIR="${VISIUM_WL_DIR:-${WL_DETECTION_RESULTS}/120525_visium_data_results}"
export LEENA_WL_DIR="${LEENA_WL_DIR:-${WL_DETECTION_RESULTS}/leena_data}"

