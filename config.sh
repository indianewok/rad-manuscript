export SCMIX2_FQ="${SCMIX2_FQ:-${RAW_FQ}/scmix2.fq.gz}"
export SPLITSEQ_FQ="${SPLITSEQ_FQ:-${RAW_FQ}/splitseq.fq.gz}"
export NBC_BCR_FQ="${NBC_BCR_FQ:-${RAW_FQ}/nbc_bcr_data.fq.gz}"
export SPATIAL_FQ="${SPATIAL_FQ:-${RAW_FQ}/spatial_tonsil_data/compiled_spatial_renamed.fq.gz}"
export LA1_FQ="${LA1_FQ:-${RAW_FQ}/la1.fq.gz}"
export LA2_FQ="${LA2_FQ:-${RAW_FQ}/la2.fq.gz}"
export LA3_FQ="${LA3_FQ:-${RAW_FQ}/la3.fq.gz}"
export LA1MEM_FQ="${LA1MEM_FQ:-${RAW_FQ}/la1mem.fastq.gz}"
export LA3MEM_FQ="${LA3MEM_FQ:-${RAW_FQ}/la3mem.fq.gz}"

# --- Per-WL paths (derived from WL_DIR) -------------------------------------
export SCTAGGER_WL="${SCTAGGER_WL:-${WL_DIR}/sctagger_bcs.csv}"
export SCMIX2_WL="${SCMIX2_WL:-${WL_DIR}/scmix2_barcodes.csv}"
export NBC_WL="${NBC_WL:-${WL_DIR}/nbc_barcodes.csv}"
export RAGESEQ_WL="${RAGESEQ_WL:-${WL_DIR}/rageseq_autogenerated_bcs.txt}"
export RAGESEQ_FULL_WL="${RAGESEQ_FULL_WL:-${WL_DIR}/rageseq_full_bcs.csv}"
