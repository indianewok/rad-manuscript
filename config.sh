#!/usr/bin/env bash
# =============================================================================
# RAD Manuscript Figure Harness — Global Configuration
# =============================================================================
# All paths in one place. There are two ways to point this file at your data:
#
#   1. Edit the defaults below directly (quick + dirty), OR
#   2. Create config.local.sh next to this file with `export VAR=...` lines —
#      it is gitignored and sourced *before* the defaults below, so anything
#      it sets wins. See config.local.sh.example for the expected shape.
#
# A few variables are also read by the R notebooks via Sys.getenv(), so every
# path variable below is `export`-ed.
# =============================================================================

SCRIPT_DIR_THIS="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# -----------------------------------------------------------------------------
# 1. Source local override first so anything it sets pre-empts the defaults.
# -----------------------------------------------------------------------------
if [ -f "${SCRIPT_DIR_THIS}/config.local.sh" ]; then
  source "${SCRIPT_DIR_THIS}/config.local.sh"
fi

# -----------------------------------------------------------------------------
# 2. Primitive paths — defaults only fire if config.local.sh didn't set them.
# -----------------------------------------------------------------------------

# --- RAD binary + thread count ----------------------------------------------
export RAD_BIN="${RAD_BIN:-/path/to/rad}"
export GEN_WL_BIN="${GEN_WL_BIN:-/path/to/rad/build/generate_whitelist}"
export RAD_THREADS="${RAD_THREADS:-4}"

# --- BLAZE / Flexiplex binaries (only needed if regenerating benchmark data) -
export BLAZE_BIN="${BLAZE_BIN:-/path/to/blaze}"

# --- Raw input FASTQs --------------------------------------------------------
export RAW_FQ="${RAW_FQ:-/path/to/raw_fqs}"

# --- Output roots ------------------------------------------------------------
export RESULTS_BASE="${RESULTS_BASE:-/path/to/results/rad/demultiplexed}"
export BLAZE_RESULTS="${BLAZE_RESULTS:-/path/to/results/blaze}"
export FLEXIPLEX_RESULTS="${FLEXIPLEX_RESULTS:-/path/to/results/flexiplex}"
export WL_DETECTION_RESULTS="${WL_DETECTION_RESULTS:-/path/to/results/rad/whitelist_detection}"

# --- Barcode whitelists ------------------------------------------------------
export WL_DIR="${WL_DIR:-/path/to/barcode_whitelists}"

# --- Analysis project root + project scripts ---------------------------------
# RAD_PAPER_DIR is the parent of WL_DIR / PROJECT_SCRIPTS and the per-run
# benchmark/timing output directories that figure_3 R scripts read from.
export RAD_PAPER_DIR="${RAD_PAPER_DIR:-/path/to/rad_paper}"
export PROJECT_SCRIPTS="${PROJECT_SCRIPTS:-${RAD_PAPER_DIR}/project_specific_scripts}"

# --- RAD source-tree resources (read layouts, kit definitions) ---------------
export RAD_RESOURCES="${RAD_RESOURCES:-/path/to/rad/resources}"

# --- Auxiliary local-only inputs --------------------------------------------
# Chr14 IGH-locus depth CSVs (Figure 5):
export NBC_DEPTH_DIR="${NBC_DEPTH_DIR:-/path/to/nbc_depth_data}"
# Engblom et al. spatial tonsil dataset (Figures 4-5):
export SWEDISH_TONSIL_DIR="${SWEDISH_TONSIL_DIR:-/path/to/swedish_tonsil_spatial}"

# -----------------------------------------------------------------------------
# 3. Derived paths — assembled after all primitives are set.
# -----------------------------------------------------------------------------

# --- Per-FASTQ paths (derived from RAW_FQ) ----------------------------------
export SCTAGGER_SIM="${SCTAGGER_SIM:-${RAW_FQ}/sctagger_sim/long-reads}"
export SCTAGGER_TRUTH="${SCTAGGER_TRUTH:-${RAW_FQ}/sctagger_sim/truth}"
